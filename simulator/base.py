# simulator/base.py
from abc import ABC, abstractmethod
from typing import Dict, Any, Optional, Tuple

import numpy as np


class ExperimentLogic(ABC):
    """
    Abstract base class for defining experiment logic.

    Randomness: stochastic models must draw random numbers from ``self.rng``
    (a ``numpy.random.Generator``), never from the global ``np.random`` state.
    The engine sets ``self.rng`` from the run's recorded seed after the model
    is constructed and before ``initialize`` is called. When a model is used
    outside the engine, :meth:`get_rng` falls back to ``config['seed']``.
    """

    rng: Optional[np.random.Generator] = None

    #: Whether outputs are generated by a model (True) or derived from loaded
    #: real data (False). Recorded as ``provenance.synthetic`` in each record.
    synthetic: bool = True

    #: How far the model's output can be trusted as reference data
    #: (see :data:`simulator.utils.FIDELITY_LEVELS`), with a short reason.
    #: Override :meth:`fidelity` when the level depends on the configuration.
    fidelity_level: str = "unverified"
    fidelity_note: Optional[str] = "No verification tests are registered for this model."

    #: Ground-truth parameters that bundles may ask to infer from the data
    #: (e.g. rate constants). Empty: no parameter-inference questions.
    inferable_parameters: Tuple[str, ...] = ()

    def fidelity(self, config: Dict[str, Any]) -> Dict[str, Any]:
        """``{"level": ..., "note": ...}`` for this configuration.

        Levels: ``reference`` (verified against closed forms, convergence or
        invariants), ``audit`` (deliberately simplified or flawed, for testing
        whether a method notices model error), ``unverified``, ``observed``
        (outputs come from real data).
        """
        return {"level": self.fidelity_level, "note": self.fidelity_note}

    # Optional: ``def invariants(self, results) -> Dict[str, array]`` returning
    # quantities that must stay constant (energy, Lotka-Volterra V, ...); the
    # model checker (simulator.checker) measures their drift.

    def mechanism_graph(self, config: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Optional causal/interaction graph of the mechanism, in node-link form::

            {"directed": True,
             "nodes": [{"id": "prey_population", "kind": "state"}, ...],
             "edges": [{"source": "predator_population", "target": "prey_population",
                        "sign": "-", "parameter": "prey_death_rate", "value": 0.4,
                        "term": "predation"}, ...]}

        Node ids should match output names. Exported in run bundles (private:
        for law-discovery tasks the graph is part of the answer).
        """
        return None

    def ground_truth_parameters(self, config: Dict[str, Any]) -> Dict[str, Any]:
        """The model parameters to export as ground truth.

        Default: every config entry that is not an engine key, not a file path
        (``*_path``/``*_file``) and is a number, bool, string or list of numbers.
        Override to export derived or internal parameters.
        """
        from .schema import ENGINE_KEYS
        params: Dict[str, Any] = {}
        for key, value in config.items():
            if key in ENGINE_KEYS or key.endswith(("_path", "_file")):
                continue
            if isinstance(value, (bool, int, float, str)) or (
                    isinstance(value, list) and all(isinstance(v, (int, float)) for v in value)):
                params[key] = value
        return params

    def get_rng(self, config: Optional[Dict[str, Any]] = None) -> np.random.Generator:
        """The engine-provided generator, or one seeded from ``config['seed']``."""
        if self.rng is None:
            seed = (config or {}).get("seed")
            self.rng = np.random.default_rng(seed)
        return self.rng

    @abstractmethod
    def initialize(self, config: Dict[str, Any]) -> Dict[str, Any]:
        """
        Initializes the simulation state.

        Args:
            config: A dictionary of configuration parameters.

        Returns:
            A dictionary representing the initial state of the simulation.
        """
        pass

    @abstractmethod
    def run_step(self, state: Dict[str, Any], step: int) -> Dict[str, Any]:
        """
        Runs a single step of the simulation.

        Args:
            state: A dictionary representing the current state of the simulation.
            step: The current simulation step number.

        Returns:
            A dictionary representing the updated state of the simulation.
        """
        pass

    @abstractmethod
    def get_results(self) -> Dict[str, Dict[str, Any]]:
        """
        Returns the simulation results.

        Returns:
            A dictionary where keys are data names and values are dictionaries
            containing the data and a DataDescriptor.
        """
        pass

    def visualize(self, results: Dict[str, Dict[str, Any]]) -> None:
        """
        Optionally provides custom visualization logic.
        """
        pass  # Default implementation does nothing


class LLMClient(ABC):
    """
    Abstract base class for interacting with LLM APIs.
    """

    @abstractmethod
    def generate_text(self, prompt: str, **kwargs) -> str:
        """
        Generates text from the LLM based on a prompt.

        Args:
            prompt: The input prompt.
            **kwargs: Additional parameters specific to the LLM provider
                      (e.g., temperature, max_tokens, model_name).

        Returns:
            The generated text.
        """
        pass

    @abstractmethod
    def generate_structured_output(self, prompt: str, schema: Dict[str, Any], **kwargs) -> Dict[str, Any]:
      """
      Generates structured output (e.g., JSON) from the LLM.

      Args:
          prompt: The input prompt
          schema: a dictionary that describes expected structure.
          **kwargs: additional parameters specific to the LLM provider.

      Returns:
          a dictionary that contains generated data.
      """
      pass

    @abstractmethod
    def get_usage_info(self) -> Dict[str, Any]:
        """
        Gets information about API usage (e.g., number of tokens used).

        Returns:
             A dictionary of usage information.
        """
        pass